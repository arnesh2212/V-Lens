"""Every figure's caption, in Markdown and in LaTeX, taken from the code.

A caption typed into the paper drifts from the figure the moment either is
touched. These are the figure functions' own docstrings, which is where the
caption has to live if it is to stay true: the person changing what a figure
draws is looking at its caption while they do it.

    python3 tools/make_captions.py
    python3 tools/make_captions.py --out CAPTIONS.md --tex paper/captions.tex
"""
from __future__ import annotations

import argparse
import glob
import inspect
import os
import re
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

#: the order a reader meets them, which is the order of the argument
ORDER = [
    ("The method, and what it costs", ["early_detection", "lens_canyon", "transport_geometry", "lens_scoreboard", "lens_scoreboard_readouts", "lens_kl", "cost_and_quality", "lens_by_depth",
                                       "lens_read_by_depth"]),
    ("Attribution over image patches", ["vwrite_baselines", "attribution_plane", "map_methods", "map_questions", "map_edits", "map_swaps", "coco_general", "patch_causal", "patch_lenses", "patch_sources",
                                        "patch_atlas", "baseline_agreement",
                                        "crossquestion", "gallery", "signed_handle"]),
    ("Writing to the model", ["steer", "direction_geometry", "handoff", "read_image",
                              "counterfactual", "carrier", "patch_jailbreak", "jailbreak_coverage_fan",
                              "refusal_steer", "refusal_read", "refusal_cascade"]),
    ("Sandbagging behind a visual password", ["pwlock_transfer", "pwlock_latent", "pwlock_conditions"]),
    ("The dataset, read through depth", ["answer_plane", "standing_plane", "packaging_lattice",
                                         "channel_plane", "commitment_lattice", "layer_story", "scene_battery", "scene_store",
                                         "authority_cases", "edit_series", "authority_ladder",
                                         "eval_series", "eval_depth", "sandbag_channels",
                                         "behaviour_directions"]),
]


#: a docstring may open with a word saying where the figure belongs
WHERE = ("MAIN", "APPENDIX")


def clean(doc: str) -> tuple[str, str, str]:
    """A docstring as (where, first line, body), rewrapped into paragraphs.

    A caption that opens with MAIN or APPENDIX is saying which part of the
    paper it is for, and that word is taken off the caption itself.
    """
    doc = inspect.cleandoc(doc or "")
    if not doc:
        return "", "", ""
    where = ""
    for w in WHERE:
        m = re.match(rf"^{w}[.:]?\s*", doc)
        if m:
            where, doc = w.lower(), doc[m.end():]
            break
    parts = doc.split("\n\n")
    lead = " ".join(parts[0].split())
    body = ["  ".join(" ".join(p.split()) for p in [q]) for q in parts[1:]]
    return where, lead, "\n\n".join(body)


def doc_of(fn) -> str:
    """A figure's caption: its ``caption()`` hook when it builds the text from the files, else its docstring."""
    hook = getattr(fn, "caption", None)
    if callable(hook):
        try:
            got = hook()
            if got:
                return got
        except Exception:  # noqa: BLE001
            pass
    return fn.__doc__ or ""


def tex_escape(s: str) -> str:
    for a, b in (("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_")):
        s = s.replace(a, b)
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="CAPTIONS.md")
    ap.add_argument("--tex", default="paper/captions.tex")
    ap.add_argument("--figures", default="figures")
    a = ap.parse_args()

    from vlens.figures import paper
    mods = [paper]
    for extra in paper.REWRITTEN:
        try:
            mods.append(__import__(f"vlens.figures.{extra}", fromlist=[extra]))
        except Exception:  # noqa: BLE001
            pass

    def find(name):
        for m in reversed(mods):          # a rewritten figure wins over the original
            fn = getattr(m, name, None)
            if fn is not None and callable(fn):
                return fn
        return None

    drawn = {os.path.basename(p).split("__")[0] for p in glob.glob(f"{a.figures}/*.png")}
    seen = set()
    md = ["# Figure captions",
          "",
          "Generated by `tools/make_captions.py` from the figure functions'",
          "docstrings. Edit the docstring, not this file.",
          "",
          "Each caption says what is shown, then what it means. Nothing in a",
          "figure states a finding; the finding is here. The bracket after each",
          "name says whether the figure is for the main paper or the appendix.",
          ""]
    tex = ["% Generated by tools/make_captions.py. Edit the docstrings, not this file.", ""]
    n = 0
    for section, names in ORDER:
        rows = [nm for nm in names if find(nm) and nm not in paper.DROPPED]
        if not rows:
            continue
        md += [f"## {section}", ""]
        for nm in rows:
            seen.add(nm)
            where, lead, body = clean(doc_of(find(nm)))
            if not lead:
                continue
            n += 1
            files = sorted(os.path.basename(p) for p in glob.glob(f"{a.figures}/{nm}*.png"))
            tag = {"main": "main paper", "appendix": "appendix"}.get(where, "unplaced")
            md.append(f"### {nm}  [{tag}]"
                      + ("  (not drawn yet)" if nm not in drawn else ""))
            md.append("")
            if files:
                md.append("Files: " + ", ".join(f"`{f}`" for f in files))
                md.append("")
            md.append(f"**{lead}**")
            md.append("")
            if body:
                md += [body, ""]
            tex.append(f"\\newcommand{{\\cap{nm.replace('_', '')}}}{{%")
            tex.append(tex_escape(lead + (" " + body.replace("\n\n", " ") if body else "")))
            tex.append("}")
            tex.append("")
    left = [nm for m in mods for nm in dir(m)
            if not nm.startswith("_") and nm not in seen
            and callable(getattr(m, nm, None))
            and (getattr(m, nm).__module__ or "").startswith("vlens.figures")
            and (getattr(m, nm).__doc__ or "").strip()
            and nm in drawn and nm not in paper.DROPPED]
    if left:
        md += ["## Not yet placed in the argument", ""]
        for nm in sorted(set(left)):
            where, lead, body = clean(doc_of(find(nm)))
            tag = {"main": "main paper", "appendix": "appendix"}.get(where, "unplaced")
            md += [f"### {nm}  [{tag}]", "", f"**{lead}**", ""] + ([body, ""] if body else [])
            n += 1
    open(a.out, "w").write("\n".join(md))
    os.makedirs(os.path.dirname(a.tex) or ".", exist_ok=True)
    open(a.tex, "w").write("\n".join(tex))
    print(f"{n} caption(s) -> {a.out} and {a.tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
